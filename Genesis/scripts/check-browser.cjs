// Run against the local API serving dist, with seeded Auth/Firestore emulators.
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
process.env.PLAYWRIGHT_BROWSERS_PATH = path.resolve('.cache/playwright');
const { chromium } = require('@playwright/test');

(async () => {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:8080');
    await page.getByRole('heading', { name: 'Investigations', exact: true }).waitFor();
    await page.locator('.case-item').first().waitFor();
    assert.equal(await page.locator('.case-item').count(), 12);
    assert.equal(await page.locator('.metric-icon svg').count(), 4);
    assert.equal(await page.locator('.metric-value').count(), 4);
    await page.getByRole('button', { name: 'Evolution lab', exact: true }).hover();
    assert.equal(await page.locator('.nav-link').nth(1).locator('.rolling-letter-track').first().evaluate(e => getComputedStyle(e).animationName), 'letter-roll');
    const delays = await page.locator('.nav-link').nth(1).locator('.rolling-letter-track').evaluateAll(nodes => nodes.slice(0, 3).map(e => getComputedStyle(e).animationDelay));
    assert.deepEqual(delays, ['0s', '0.024s', '0.048s']);
    assert.equal(await page.locator('main .rolling-label').count(), 0);
    await page.getByRole('textbox', { name: 'Search cases' }).fill('no-matching-case-xyz');
    await page.getByText('No matching cases', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Clear search', exact: true }).first().click();
    assert.equal(await page.locator('.case-item').count(), 12);
    assert.equal(await page.getByRole('textbox', { name: 'Search cases' }).evaluate(e => e === document.activeElement), true);
    await page.getByRole('textbox', { name: 'Search cases' }).fill('structuring');
    await page.locator('.case-item').click();
    await page.getByText(/Protected signals: structuring/).waitFor();
    assert.equal(await page.locator('.workflow-step.complete>span').first().evaluate(e => getComputedStyle(e).backgroundColor), 'rgb(24, 116, 94)');
    assert.deepEqual(await page.locator('.track').evaluateAll(nodes => [...new Set(nodes.map(e => getComputedStyle(e).height))]), ['6px']);
    await page.getByRole('button', { name: 'Clear search', exact: true }).click();
    fs.mkdirSync('.cache/preview', { recursive: true });
    await page.locator('.sidebar').evaluate(el => Promise.all(el.getAnimations({ subtree: true }).map(animation => animation.finished.catch(() => {}))));
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: '.cache/preview/desktop.png', fullPage: true });
    await page.getByRole('textbox', { name: 'Search cases' }).fill('incomplete');
    await page.locator('.case-item').click();
    await page.getByText('Context requires attention').waitFor();
    assert.equal(await page.locator('.score').innerText(), '— / 1.00');
    await page.getByRole('button', { name: /Public visitor/ }).click();
    await page.screenshot({ path: '.cache/preview/signin.png' });
    await page.getByLabel('Email', { exact: true }).fill('invalid');
    await page.getByRole('button', { name: 'Sign in locally' }).click();
    await page.getByText('Enter a valid email address.').waitFor();
    await page.getByLabel('Email', { exact: true }).fill('operator@aml-insight.test');
    await page.getByRole('button', { name: 'Show password' }).click();
    assert.equal(await page.getByLabel('Password', { exact: true }).getAttribute('type'), 'text');
    await page.getByRole('button', { name: 'Hide password' }).click();
    await page.getByLabel('Password', { exact: true }).fill('incorrect-local-password');
    await page.getByRole('button', { name: 'Sign in locally' }).click();
    await page.getByRole('alert').filter({ hasText: 'Local sign-in failed' }).waitFor();
    assert.equal(await page.getByLabel('Email', { exact: true }).inputValue(), 'operator@aml-insight.test');
    await page.getByLabel('Password', { exact: true }).fill('local-demo-only');
    await page.getByRole('button', { name: 'Sign in locally' }).click();
    await page.getByRole('button', { name: /Local operator/ }).waitFor();
    await page.getByRole('button', { name: 'Check live triage' }).click();
    await page.getByRole('alert').filter({ hasText: 'no model request was sent' }).waitFor();
    await page.getByRole('button', { name: /Evolution lab/ }).click();
    await page.getByRole('button', { name: /Feedback snapshot/ }).hover();
    await page.locator('#workflow-explanation').getByRole('heading', { name: 'Feedback snapshot' }).waitFor();
    await page.locator('#workflow-explanation').getByText(/immutable snapshot/).waitFor();
    await page.getByRole('button', { name: /Independent evaluation/ }).focus();
    await page.locator('#workflow-explanation').getByText(/held-out cases/).waitFor();
    await page.getByRole('button', { name: /Reviewed cases/ }).click();
    await page.getByRole('button', { name: 'Run discovery diagnostic' }).click();
    await page.getByRole('cell', { name: 'expected-activity', exact: true }).waitFor();
    await page.locator('.sidebar').evaluate(el => Promise.all(el.getAnimations({ subtree: true }).map(animation => animation.finished.catch(() => {}))));
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: '.cache/preview/evolution.png', fullPage: true });
    await page.getByRole('button', { name: /System design/ }).click();
    await page.getByRole('heading', { name: 'Six roles. Explicit handovers.' }).waitFor();
    assert.equal(await page.locator('tbody tr').count(), 6);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: /Evolution lab/ }).click();
    await page.getByRole('button', { name: /Candidate proposal/ }).click();
    await page.locator('#workflow-explanation').getByText(/versioned candidate/).waitFor();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile workflow must not overflow');
    await page.screenshot({ path: '.cache/preview/mobile-evolution.png', fullPage: true });
    await page.getByRole('button', { name: /Investigations/ }).click();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile page must not overflow horizontally');
    await page.screenshot({ path: '.cache/preview/mobile.png', fullPage: true });
    await page.getByRole('button', { name: /Local operator/ }).click();
    await page.getByRole('button', { name: /Public visitor/ }).click();
    await page.getByRole('dialog').waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog').count(), 0);
    assert.notEqual(await page.evaluate(() => getComputedStyle(document.documentElement).scrollbarColor), 'auto');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await page.locator('.nav-link').first().evaluate(e => getComputedStyle(e).transitionDuration), '0s');
    assert.equal(await page.locator('.rolling-letter-track').first().evaluate(e => getComputedStyle(e).animationName), 'none');
    assert.equal(await page.locator('.nav-selection').evaluate(e => getComputedStyle(e).transitionDuration), '0s');

    const states = await browser.newPage({ viewport: { width: 390, height: 844 } });
    let release;
    await states.route('**/api/demo/alerts', async route => {
      await new Promise(resolve => { release = resolve; });
      await route.fulfill({ json: { cases: [] } });
    });
    await states.goto('http://127.0.0.1:8080');
    await states.getByRole('status').filter({ hasText: 'Loading published evidence' }).waitFor();
    release();
    await states.getByRole('heading', { name: 'Your workspace is ready for data.' }).waitFor();
    await states.unroute('**/api/demo/alerts');
    await states.route('**/api/demo/alerts', route => route.abort('internetdisconnected'));
    await states.getByRole('button', { name: 'Retry connection' }).click();
    await states.getByRole('alert').filter({ hasText: 'Unable to reach the service' }).waitFor();
    await states.unroute('**/api/demo/alerts');
    await states.getByRole('button', { name: 'Retry connection' }).click();
    await states.locator('.case-item').first().waitFor();
    assert.equal(await states.locator('.case-item').count(), 12);
    await states.close();
    assert.deepEqual(errors, [], 'No browser JavaScript errors');
    console.log('Browser check passed: staggered sidebar roll, metric icons, uniform bars, green completion, workflow hover/focus/tap, investigations, auth, discovery, mobile, reduced motion, loading/empty/offline/retry.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
